#!/usr/bin/env python3
"""Embed navigation PCM sounds and the xmb-web wave loop videos in ONE ELF.

Generates a small GNU-as compatible .s with .incbin statements, not gigantic
C++ hex arrays. The PS5 sdk uses clang's x86_64 assembler and linker. Both
zt_shellui and the loader's embedded zt_shellui module have these bytes.

The ELF installer copies them to the active ZhiThemes wallpaper directory on
startup, before any HomeUI JS begins playback. No upload script or IP needed.
"""
from pathlib import Path
import argparse, hashlib, json
R=Path(__file__).resolve().parents[1]
ASSETS=(
  ('snd_cursor','PS3_snd_cursor.s16le'),            # original PS3 XMB sounds (owner-supplied), see make_ps3_sfx.py
  ('snd_category','PS3_snd_category_decide.s16le'),
  ('snd_decide','PS3_snd_decide.s16le'),
  ('snd_cancel','PS3_snd_cancel.s16le'),
  ('snd_ok','PS3_snd_system_ok.s16le'),
  ('snd_ng','PS3_snd_system_ng.s16le'),
  ('wave_day','PS5XMB_XMBWEB_Wave_Day.mp4'),      # xmb-web wave, rendered from its own WebGL shader
  ('wave_night','PS5XMB_XMBWEB_Wave_Night.mp4'),
  ('wave_day_blur','PS5XMB_XMBWEB_Wave_Day_Blur.mp4'),     # V56: the same loops blurred (PS3 submenu background), 960x540
  ('wave_night_blur','PS5XMB_XMBWEB_Wave_Night_Blur.mp4'),
)

def incbin_quoted(path):
    s=str(path)
    if '\n' in s or '\r' in s: raise ValueError('Unsafe pathname')
    return '"'+s.replace('\\','\\\\').replace('"','\\"')+'"'

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--verify-only',action='store_true')
    a=ap.parse_args()
    output=R/'src/source/shellui/src/zt_xmb_embedded_media.s'
    lines=['/* Auto generated by xmb_patch/embed_media.py — no manual upload. */',
           '.section .rodata.zt_xmb_media,"a",@progbits', '.p2align 4']
    report={}
    for key,name in ASSETS:
        p=(R/'ps3_assets'/name).resolve(strict=True)
        if p.stat().st_size < (2000 if not name.endswith('.s16le') else 1024): raise ValueError('Media file too small: '+name)
        if p.stat().st_size > 64_000_000: raise ValueError('Media file too large: '+name)
        report[key]={'file':name,'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()}
        lines += [f'.globl zt_xmb_{key}_start',f'.globl zt_xmb_{key}_end',
                  f'.type zt_xmb_{key}_start,@object',
                  f'zt_xmb_{key}_start:',f'  .incbin {incbin_quoted(p)}',
                  f'zt_xmb_{key}_end:', '.p2align 4']
    # V83.14: only Rodin Regular is embedded; all text weights use that one file.
    # artwork. The PATCH does not redistribute fonts; the local WSL build adds them
    # directly to the payload with .incbin (same mechanism as the existing videos).
    defaults=(
      ('font_regular','fonts/ps3-rodin-regular.ttf'),
      ('glow_l','glow/glow_l.png'),
      ('glow_m','glow/glow_m.png'),
      ('glow_r','glow/glow_r.png'),
    )
    for key, rel in defaults:
        p=R/'xmb_patch/native_assets'/rel
        if not p.is_file():
            raise SystemExit('V83.8 missing local XMB asset: '+str(p)+'\nRestore the original file under xmb_patch/native_assets before building.')
        size=p.stat().st_size
        magic=p.open('rb').read(8)
        if key.startswith('font_'):
            if size < 2048 or size > 4_000_000 or magic[:4] not in (b'\x00\x01\x00\x00',b'true'):
                raise SystemExit('V83.8: not a valid TrueType font: '+str(p))
        else:
            if size < 64 or size > 2_000_000 or magic != b'\x89PNG\r\n\x1a\n':
                raise SystemExit('V83.8: not a valid glow PNG: '+str(p))
        p=p.resolve()
        report[key]={'file':str(p.relative_to(R)),'bytes':size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()}
        lines += [f'.globl zt_xmb_{key}_start',f'.globl zt_xmb_{key}_end',
                  f'.type zt_xmb_{key}_start,@object',
                  f'zt_xmb_{key}_start:',f'  .incbin {incbin_quoted(p)}',
                  f'zt_xmb_{key}_end:', '.p2align 4']
    lines += ['.section .note.GNU-stack,"",@progbits','']
    content='\n'.join(lines)
    if a.verify_only:
        if output.read_text()!=content:raise SystemExit('Stale embedded media assembly. Run embed_media.py')
    else:
        output.write_text(content)
        (R/'ps3_assets/embedded_media_manifest.json').write_text(json.dumps(report,indent=2)+'\n')
    print('ONE ELF navigation audio + wave loops:', {k:v['bytes'] for k,v in report.items()},'assembly=',output.name)
if __name__=='__main__':main()
